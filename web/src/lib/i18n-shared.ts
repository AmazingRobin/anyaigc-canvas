export type SharedLanguage = LanguageName;

function currentLanguage(language?: SharedLanguage): SharedLanguage {
    return language ?? useLanguageStore.getState().language;
}

function compactKey(value: string): string {
    return value.replace(/[\s·，。、“”「」：:（）()\/.-]/g, "");
}

export function sharedText(zh: string, en?: string, language?: SharedLanguage): string {
    if (currentLanguage(language) !== "en") return zh;
    if (en) return en;
    return sharedZhToEn[compactKey(zh) as keyof typeof sharedZhToEn] ?? sharedZhToEn[zh as keyof typeof sharedZhToEn] ?? zh;
}

export function sharedErrorText(value: string, language?: SharedLanguage): string {
    if (currentLanguage(language) !== "en") return value;
    const exact = sharedText(value, undefined, language);
    if (exact !== value) return exact;
    const separator = value.indexOf("：");
    if (separator > 0) {
        const prefix = value.slice(0, separator);
        const translatedPrefix = sharedText(prefix, undefined, language);
        if (translatedPrefix !== prefix) return `${translatedPrefix}: ${value.slice(separator + 1).trim()}`;
    }
    if (value.startsWith("云同步请求超时：")) {
        const detail = value.slice("云同步请求超时：".length).replace(/，请稍后重试$/, "").replaceAll("，", ", ");
        return `Cloud sync request timed out: ${detail}. Try again later.`;
    }
    if (value.endsWith(" 同步清单不是当前应用的数据")) {
        return `${value.slice(0, -" 同步清单不是当前应用的数据".length)} sync manifest does not belong to this app`;
    }
    return value;
}

export function sharedFormatDate(value: string | number | Date, language?: SharedLanguage, options: Intl.DateTimeFormatOptions = { year: "numeric", month: "2-digit", day: "2-digit" }): string {
    const date = value instanceof Date ? value : new Date(value);
    if (Number.isNaN(date.getTime())) return "";
    return new Intl.DateTimeFormat(currentLanguage(language) === "en" ? "en-US" : "zh-CN", options).format(date);
}
